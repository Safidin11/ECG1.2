"""Калибровочный импульс: масштаб по амплитуде, когда сетки нет.

Зачем. Милливольты получаются из пикселей через масштаб плёнки, а масштаб
движок берёт из миллиметровки — считает период сетки. Если сетки нет (распечатка
из ЕМИАС, снимок экрана, бланк без клеток), брать масштаб неоткуда, и он
угадывается по косвенным признакам. Ошибка тут уходит в милливольты один к
одному: промах масштаба на 20% — это промах по всем амплитудам на 20%.

Но у самой плёнки есть эталон, который кардиограф печатает специально для
этого: калибровочный импульс. Прямоугольная ступенька в начале каждой строки,
и её высота по определению равна 1 мВ. Это заявление прибора о собственном
усилении — источник honestнее сетки: сетка говорит про бумагу, импульс про
сигнал. Если печатали в половинном усилении, сетка об этом не знает, а импульс
знает.

Мерить его приходится отдельно от движка: его трассировщик на вертикальных
фронтах рвётся и импульс просто пропускает — в сырых линиях он начинается уже
ПОСЛЕ ступеньки. Поэтому читаем прямо с картинки.

Форма импульса — П: подъём, плато, спуск. Ищем по ней:
  * плато — длинный горизонтальный ряд чернил, его легко узнать по длине;
  * основание — уровень, с которого он поднялся.
Высота = расстояние между ними.

Demo-инструмент, НЕ медизделие.
"""
from __future__ import annotations

import cv2
import numpy as np

MM_PER_MV = 10.0            # стандартное усиление: 1 мВ = 10 мм плёнки
# Доля ширины окна, которую должен занимать ряд чернил, чтобы считаться плато.
# Плато импульса — это 1-2 мм по времени при высоте 10 мм, то есть отношение
# сторон около 1:5; более короткие ряды дают зубцы, более длинные — изолиния.
PLATEAU = 0.35
# Высота импульса в долях расстояния между строками плёнки. Проверка нарочно
# БЕЗ миллиметров: масштаб — это как раз то, что мы ищем, и опираться на него
# было бы кругом. А отношение к шагу строк известно из устройства плёнки:
# импульс 10 мм, а на строку отводится от 12 мм (двенадцать строк на одном
# листе, как в выгрузке 12x1) до 45 мм (раскладка 3x4). Отсекает мусор вроде
# «импульс 15 px при шаге строк 250» — это не импульс, а линия сетки.
MIN_SHARE, MAX_SHARE = 0.18, 0.95


def ink_mask(gray: np.ndarray, k: float = 0.45) -> np.ndarray:
    """Где чернила. Порог местный: фон на фото неровный, и общий порог съедает
    то светлую часть кадра, то тёмную.

    Коэффициент k подбирается снаружи перебором, и это не лень. Одного порога
    на все входы не существует: на бумаге надо отсечь бледную миллиметровку,
    иначе профиль по столбцам превращается в гребёнку из её линий и импульс в
    ней тонет; а на снимке экрана тот же строгий порог срезает и сам импульс,
    потому что муар задирает верхний перцентиль, по которому порог считается.
    """
    bg = cv2.morphologyEx(gray, cv2.MORPH_CLOSE,
                          cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (15, 15)))
    diff = cv2.subtract(bg, gray).astype(np.float32)
    return diff > max(10.0, k * float(np.percentile(diff, 99.5)))


def _shapes(ink: np.ndarray, x_lo: int, x_hi: int) -> list[tuple[int, int, int]]:
    """Отдельные фигуры в зоне импульса: (высота, ширина, верх).

    Режем картинку по правому краю зоны, чтобы импульс отделился от трассы:
    напечатаны они одной линией и в целой картинке представляют собой одну
    связную фигуру длиной во всю строку.

    Через связные компоненты, а не через профили строк. Профили пробовал —
    получалось то 26 px, то 109 при настоящих 106: у буквы П верх и низ дают
    два всплеска, между ними пусто, и любое правило «сверху донизу» цепляло то
    половину своего импульса, то кусок соседней строки. Фигура целиком таких
    вопросов не задаёт.
    """
    sub = (ink[:, x_lo:x_hi] * 255).astype(np.uint8)
    n, _, st, _ = cv2.connectedComponentsWithStats(sub, 8)
    return [(int(st[i, cv2.CC_STAT_HEIGHT]), int(st[i, cv2.CC_STAT_WIDTH]),
             int(st[i, cv2.CC_STAT_TOP])) for i in range(1, n)
            if st[i, cv2.CC_STAT_AREA] >= 40]


def pulse_window(ink: np.ndarray) -> tuple[int, int] | None:
    """Где на плёнке стоят импульсы — по столбцам чернил.

    Импульс — вертикальный штрих во всю свою высоту, и в каждой строке плёнки
    он свой. Двенадцать таких штрихов, стоящих друг под другом, дают в профиле
    по столбцам заметный горб слева. Ровная изолиния столько чернил не даёт:
    её толщина в разы меньше высоты импульса.
    """
    col = ink.sum(0).astype(float)
    if not col.any():
        return None
    mid = col[int(0.35 * len(col)):int(0.9 * len(col))]
    trace = float(np.median(mid[mid > 0])) if (mid > 0).any() else 0.0
    if trace <= 0:
        return None
    left = col[:int(0.30 * len(col))]
    hot = left > 1.5 * trace
    if not hot.any():
        return None
    # Берём первый сплошной кусок: правее могут быть подписи отведений, они
    # тоже дают чернила, но уже после импульса.
    d = np.diff(np.concatenate([[0], hot.view(np.int8), [0]]))
    s, e = np.flatnonzero(d == 1), np.flatnonzero(d == -1)
    k = int(np.argmax(e - s))
    return int(s[k]), int(e[k])


def trace_rows(ink: np.ndarray, x_from: int) -> list[int]:
    """Уровни изолиний строк плёнки — по трассе СПРАВА от импульса.

    Искать строки по самой зоне импульса нельзя: у буквы П верх и низ дают в
    горизонтальном профиле два отдельных всплеска, и каждая строка распадалась
    на две. Справа же лежит ровная изолиния — по одному всплеску на строку.
    """
    x_to = min(ink.shape[1], x_from + max(80, ink.shape[1] // 4))
    if x_to - x_from < 20:
        return []
    rows = ink[:, x_from:x_to].sum(1).astype(float)
    hot = rows > 0.35 * (x_to - x_from)
    d = np.diff(np.concatenate([[0], hot.view(np.int8), [0]]))
    s, e = np.flatnonzero(d == 1), np.flatnonzero(d == -1)
    return [int((a + b) // 2) for a, b in zip(s, e) if b - a >= 2]


def find_pulse(gray: np.ndarray) -> dict | None:
    """Высота калибровочного импульса, пикселей.

    Перебираем несколько порогов чернил и берём тот, на котором семейство
    импульсов сошлось лучше всего: больше строк согласились между собой при
    меньшем разбросе. Это и есть признак, что нашли именно импульс, — он
    печатается одинаковым во всех строках, а всё остальное на плёнке разное.
    """
    best = None
    for k in (0.25, 0.35, 0.45, 0.60):
        r = _find_pulse_at(gray, k)
        if r and (best is None or
                  (r["n_rows"], -r["spread_px"]) > (best["n_rows"], -best["spread_px"])):
            best = r
    return best


def _find_pulse_at(gray: np.ndarray, k: float) -> dict | None:
    ink = ink_mask(gray, k)
    win = pulse_window(ink)
    if win is None:
        return None
    x_lo, x_hi = win
    ys = trace_rows(ink, x_hi)
    if len(ys) < 3:
        return None
    pitch = float(np.median(np.diff(ys)))
    shapes = _shapes(ink, x_lo, x_hi)
    if len(shapes) < 3 or pitch <= 0:
        return None

    # Импульсы одинаковы во всех строках, поэтому ищем не «самую большую
    # фигуру», а САМУЮ ПОВТОРЯЮЩУЮСЯ высоту: соседние строки могут слипнуться
    # в одну фигуру двойной высоты, край плёнки — обрезать фигуру, а подпись
    # отведения дать мелкую. Всё это единичные случаи, а импульс — семейство.
    hs = np.array([h for h, w, _ in shapes
                   if h >= 8 and w >= 0.25 * (x_hi - x_lo)
                   and MIN_SHARE * pitch <= h <= MAX_SHARE * pitch], dtype=float)
    if len(hs) < 3:
        return None
    best, keep = None, None
    for h in hs:
        near = hs[np.abs(hs - h) <= max(2.0, 0.12 * h)]
        if best is None or len(near) > len(best):
            best, keep = near, h
    if best is None or len(best) < 3:
        return None
    h = float(np.median(best))
    return {"px": h, "n_rows": int(len(best)), "x": [x_lo, x_hi], "k": k,
            "row_pitch_px": pitch,
            "spread_px": float(np.median(np.abs(best - h)))}


DISAGREE = 0.15             # расхождение с сеткой, после которого ей не верим


def scale_from_pulse(pulse_px: float, px_per_mm_grid: float) -> dict | None:
    """Масштаб по импульсу и сверка с масштабом сетки.

    Эталон здесь ИМПУЛЬС, а не сетка. Импульс по определению 10 мм = 1 мВ, это
    заявление самого прибора; сетка же говорит только про бумагу, и когда её
    нет, движок всё равно выдаёт какое-то число — оно и оказывается вымыслом.
    На плёнке из ЕМИАС сетки нет: движок насчитал 4.75 px/мм, импульс говорит
    10.6, и это не мелочь — вдвое неверные и амплитуды, и длительности.

    Возвращает множитель, на который надо умножить милливольты, посчитанные по
    сетке, чтобы получить настоящие.
    """
    if not pulse_px or pulse_px <= 0:
        return None
    px_per_mm = pulse_px / MM_PER_MV
    out = {"px_per_mm": px_per_mm, "pulse_px": pulse_px}
    if px_per_mm_grid <= 0:
        return out | {"factor": None, "agrees": False}
    ratio = px_per_mm_grid / px_per_mm
    return out | {"grid_px_per_mm": px_per_mm_grid, "ratio": ratio,
                  # больше пикселей на милливольт, чем думала сетка -> сетка
                  # завысила милливольты, множитель меньше единицы
                  "factor": ratio,
                  "agrees": abs(ratio - 1.0) <= DISAGREE}
