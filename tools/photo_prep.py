"""Подготовка фотографии ЭКГ: выровнять освещение, вытянуть чернила.

Общий принцип здесь один, и он не про «покрутить яркость и контраст».

Яркость и контраст — это ОДНА поправка на весь кадр. А беда фотографии в том,
что засветка на ней РАЗНАЯ в разных местах: блик от лампы, тень от руки,
завал по краям, подсветка экрана ярче в середине. Одной поправкой это не
лечится: вытянешь тёмный угол — выбьешь блик в белое, прижмёшь блик — утопишь
угол в чёрное. Именно поэтому ручная крутилка «блеска» иногда помогает, а
иногда делает хуже: она угадывает одно число там, где нужно поле чисел.

Правильная поправка — местная. Снимок устроен как

    что видно  =  сколько света упало  x  насколько поверхность отражает

Нужен второй множитель: бумага белая, чернила тёмные, и это не зависит от
лампы. Первый множитель — освещение — меняется плавно, на масштабе всего
кадра, а чернила тонкие. Значит освещение можно ОЦЕНИТЬ по самому снимку:
взять его же копию, из которой убраны все тонкие тёмные детали, и поделить
одно на другое. Деление, а не вычитание, потому что связь между ними
умножительная.

    фон = снимок, из которого убраны тонкие тёмные линии
    чисто = снимок / фон

После деления каждая точка меряется относительно СВОЕЙ окрестности: «на
сколько здесь темнее, чем бумага рядом». Блик перестаёт быть бликом, тень —
тенью, и остаётся ровно то, что нам нужно, — где чернила.

Второй принцип — про уменьшение. Снимок экрана несёт муар: пиксельная решётка
матрицы бьётся о решётку сенсора камеры, и получаются широкие полосы. Муар —
это НЕДОСТАТОК СГЛАЖИВАНИЯ при переходе с одной решётки на другую, и лечится
он тем же, чем везде: сгладить ПЕРЕД тем, как уменьшать. Порядок здесь решает
всё. Уменьшить, а потом чистить — поздно, полосы уже въелись в новые пиксели и
неотличимы от сигнала. Проверено на снимке экрана из ЕМИАС: если сначала
выровнять освещение, а потом уменьшить, фон уходит в серую рябь; если сначала
сгладить и уменьшить, а выровнять после — бумага белая, линия чёткая.

Тонкие тёмные детали убираем морфологическим закрытием, а не размытием.
Размытие фон бы занизило: тёмная линия тянет среднее вниз, и рядом с жирным
комплексом «бумага» оказывается темнее, чем на пустом месте, — деление там
недожимает. Закрытие сначала расширяет светлое, съедая всё тёмное тоньше
кисти, и только потом возвращает границы на место: линии исчезают, а форма
освещения остаётся.

ЧТО ПОКАЗАЛ ЗАМЕР. В конвейер это НЕ включено, и вот почему. Взяли чистую
плёнку PTB-XL, испортили освещение нарочно и сильно — блик от лампы, тень от
руки, завал по краям, яркость фона гуляет от 0.39 до 1.41, — и прогнали дважды:

                    корреляция   зубец R   покрытие   цена раскладки
    без обработки      0.993      0.991      0.292        0.09
    с обработкой       0.993      0.994      0.292        0.10

То есть ничего. Причина простая: U-Net движка обучен на настоящих фотографиях,
и блики с тенями — ровно то, что он видел при обучении. Мы чистим то, что он и
так умеет игнорировать. На снимке экрана из ЕМИАС результат такой же: покрытие
строк 11.33 против 11.38 из 12, зато цена раскладки уехала в бесконечность —
растяжка контраста подъедает мелкие подписи отведений, а по ним движок формат и
опознаёт. Так что включать по умолчанию нельзя: пользы нет, вред есть.

Модуль оставлен как измеренный результат и как инструмент на случай входа,
которому это действительно понадобится. Реально на разбор влияют другие вещи:
ЧТО попало в кадр (лишний блок с заключением рядом ломает всё) и СКОЛЬКО
деталей в снимке (пикселей на миллиметр плёнки).

Demo-инструмент, НЕ медизделие.
"""
from __future__ import annotations

import cv2
import numpy as np

# Кисть закрытия в долях короткой стороны кадра. Должна быть заведомо толще
# линии ЭКГ и заведомо тоньше перепадов освещения: линии — доли процента кадра,
# блики и тени — десятки процентов.
BRUSH = 0.025
# Куда растягиваем итог. Не до чистого белого: у движка обучение шло на фото,
# где бумага не идеально белая, и выжженный фон ему непривычен.
PAPER = 235


def _odd(n: int) -> int:
    return max(3, int(n) | 1)


def illumination(gray: np.ndarray, brush: float = BRUSH) -> np.ndarray:
    """Оценка освещения: снимок без тонких тёмных деталей."""
    k = _odd(brush * min(gray.shape[:2]))
    bg = cv2.morphologyEx(gray, cv2.MORPH_CLOSE,
                          cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (k, k)))
    # Лёгкое размытие после закрытия: оно оставляет ступеньки на границах
    # кисти, и без сглаживания эти ступеньки проступят в результате деления.
    return cv2.GaussianBlur(bg, (_odd(k // 2), _odd(k // 2)), 0)


def flatten(img: np.ndarray, brush: float = BRUSH) -> np.ndarray:
    """Убрать неровное освещение делением на его оценку."""
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY) if img.ndim == 3 else img
    bg = illumination(gray, brush).astype(np.float32)
    flat = gray.astype(np.float32) / np.maximum(bg, 1.0)
    return np.clip(flat, 0.0, 1.5)


def stretch(flat: np.ndarray, dark_pct: float = 0.4) -> np.ndarray:
    """Растянуть контраст по перцентилю самых тёмных точек.

    Нижнюю границу берём не по минимуму, а по перцентилю: одна чёрная пылинка
    или прожжённый пиксель матрицы иначе задирали бы весь диапазон и вся
    картинка выцветала. Верхняя граница — единица по построению: после деления
    бумага равна своему же фону.
    """
    lo = float(np.percentile(flat, dark_pct))
    out = (flat - lo) / max(1.0 - lo, 1e-6)
    return (np.clip(out, 0, 1) * PAPER).astype(np.uint8)


def enhance(img: np.ndarray, brush: float = BRUSH,
            unsharp: float = 0.6) -> np.ndarray:
    """Фото -> картинка, на которой чернила видно ровно везде.

    Возвращает трёхканальную (движок ждёт BGR), но по сути серую: цвет для
    поиска линии бесполезен, а на снимке экрана он вдобавок несёт муар от
    субпикселей матрицы.
    """
    out = stretch(flatten(img, brush))
    if unsharp > 0:
        # Нерезкое маскирование маленьким радиусом: возвращает тонкой линии
        # чёткость, потерянную при съёмке и сжатии. Радиус маленький намеренно,
        # большой начал бы обводить комплексы светлым ореолом.
        blur = cv2.GaussianBlur(out, (0, 0), 1.2)
        out = cv2.addWeighted(out, 1 + unsharp, blur, -unsharp, 0)
    return cv2.cvtColor(out, cv2.COLOR_GRAY2BGR)


def prepare(img: np.ndarray, target_w: int, brush: float = 0.008) -> np.ndarray:
    """Полный порядок действий: сгладить -> уменьшить -> выровнять освещение.

    Порядок важнее самих операций. Сглаживание идёт ДО уменьшения, иначе муар
    и мелкая зернистость превращаются в полосы, неотличимые от сигнала.
    Выравнивание идёт ПОСЛЕ, иначе оно растягивает контраст этих же полос и
    делает только хуже — так и вышло при первой попытке.
    """
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY) if img.ndim == 3 else img
    k = img.shape[1] / max(target_w, 1)
    if k > 1.15:
        # Радиус сглаживания привязан к КРАТНОСТИ уменьшения: именно она
        # задаёт, какие частоты не переживут прореживание.
        gray = cv2.GaussianBlur(gray, (0, 0), 0.5 * k)
        h = max(1, int(round(gray.shape[0] / k)))
        gray = cv2.resize(gray, (target_w, h), interpolation=cv2.INTER_AREA)
    return enhance(cv2.cvtColor(gray, cv2.COLOR_GRAY2BGR), brush=brush, unsharp=0.0)


def has_grid(img: np.ndarray) -> bool:
    """Есть ли на снимке миллиметровка.

    Смотрим спектр строк и столбцов: у сетки период строго постоянный, и в
    спектре стоит острый пик. У кривой ЭКГ, текста и муара такого пика нет —
    муар как раз плавает по кадру, и его пик размазан.

    Нужно затем, что без сетки масштаб брать неоткуда, кроме калибровочного
    импульса, — и об этом надо знать заранее.
    """
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY) if img.ndim == 3 else img
    g = cv2.resize(gray, (512, 512)).astype(np.float32)
    g -= cv2.GaussianBlur(g, (0, 0), 8)             # убрать плавный фон
    peaks = []
    for prof in (g.mean(0), g.mean(1)):
        sp = np.abs(np.fft.rfft(prof * np.hanning(len(prof))))
        sp[:6] = 0                                   # медленные составляющие
        if sp.max() > 0:
            peaks.append(float(sp.max() / (np.median(sp) + 1e-9)))
    return bool(peaks) and min(peaks) > 12.0
