#!/usr/bin/env bash
# Открыть сайт наружу — чтобы зайти с телефона по мобильному интернету,
# а не только по домашнему Wi-Fi.
#
#   tools/share.sh                 # порт 5050 по умолчанию
#   tools/share.sh 5051
#
# Печатает публичный адрес вида https://что-то.lhr.life. Пока скрипт работает —
# адрес живой; закрыл окно, и адрес умер. Ни регистрации, ни установки.
#
# ВНИМАНИЕ: адрес публичный. Кто угодно, кому он попадёт, сможет загружать
# картинки на эту машину, пока туннель открыт. Для «показать знакомому» это
# нормально, для чего-то большего нужен хостинг с ограничением доступа.
set -euo pipefail

PORT="${1:-5050}"

if ! curl -sf -o /dev/null "http://127.0.0.1:$PORT/"; then
  echo "На порту $PORT никто не отвечает. Сначала запусти сайт, в отдельном окне:"
  echo "  ./.venv/bin/python service/app.py"
  exit 1
fi

cat <<TXT
Поднимаю туннель на порт $PORT. Через несколько секунд ниже появится строка
вида  https://xxxxx.lhr.life  — это и есть адрес для телефона.
Остановить: Ctrl+C.

TXT

# Через SSH, а не через cloudflared, и вот почему. cloudflared ищет свои сервера
# SRV-запросом, а его встроенный резолвер читает /etc/resolv.conf, которого на
# macOS попросту нет: настройки DNS лежат в системной конфигурации. Резолвер
# уходит на localhost, где никто не слушает, и туннель падает с
# "lookup _v2-origintunneld._tcp.argotunnel.com on [::1]:53: connection refused".
# Лечится созданием /etc/resolv.conf, но это правка системного файла под sudo
# ради одной программы. У ssh таких проблем нет — он спрашивает систему.
exec ssh -o StrictHostKeyChecking=accept-new \
         -o ServerAliveInterval=30 -o ExitOnForwardFailure=yes \
         -R "80:127.0.0.1:$PORT" nokey@localhost.run
